// @vitest-environment jsdom
import {afterEach,beforeEach,describe,expect,it,vi} from 'vitest'
import {act,fireEvent,render,renderHook,screen,cleanup} from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import {StarPet,petImage,usePetIdleMs} from './StarPet'

beforeEach(()=>{localStorage.clear()})
afterEach(()=>{cleanup();vi.restoreAllMocks();vi.useRealTimers()})
describe('Star mascot',()=>{
 it('maps all activity states to approved art names',()=>{
  expect(petImage('idle').face).toBe('normal')
  expect(petImage('idle',true).face).toBe('content')
  expect(petImage('typing').face).toBe('focused')
  expect(petImage('thinking').pose).toBe('think')
  expect(petImage('streaming').pose).toBe('type-1')
  expect(petImage('streaming',true).pose).toBe('type-2')
  expect(petImage('finished').face).toBe('happy')
  expect(petImage('error').face).toBe('nervous')
  expect(petImage('cancelled').face).toBe('surprised')
  expect(petImage('sleepy').face).toBe('sleepy')
  expect(petImage('asleep').face).toBe('asleep')
  expect(petImage('update').pose).toBe('letter')
 })
 it.each(['idle','typing','thinking','streaming','finished','error','cancelled','sleepy','asleep','update'] as const)('keeps %s artwork relative to the packaged entry point',state=>{
  const {container}=render(<StarPet state={state} reducedMotion/>)
  const src=container.querySelector('img')!.getAttribute('src')!
  expect(src).toMatch(/^\.\/mascot\//)
  expect(new URL(src,'file:///app/frontend/dist/index.html').href).toMatch(/^file:\/\/\/app\/frontend\/dist\/mascot\//)
 })
 it('hides entirely when disabled and stops all pet timers',()=>{
  vi.useFakeTimers()
  const {rerender}=render(<StarPet state="idle"/>)
  expect(screen.getByTestId('star-pet')).toBeTruthy()
  expect(vi.getTimerCount()).toBe(2)
  rerender(<StarPet state="idle" visible={false}/>)
  expect(screen.queryByTestId('star-pet')).toBeNull()
  expect(vi.getTimerCount()).toBe(0)
 })
 it('hides when artwork is missing',()=>{
  render(<StarPet state="idle"/>)
  fireEvent.error(document.querySelector('.star-pet__image') as HTMLImageElement)
  expect(screen.queryByTestId('star-pet')).toBeNull()
 })
 it('does not alternate art with reduced motion',()=>{
  vi.useFakeTimers()
  const {container}=render(<StarPet state="streaming" reducedMotion/>)
  expect(container.querySelector('.star-pet__image')?.getAttribute('src')).toBe('./mascot/poses/type-1.png')
  act(()=>vi.advanceTimersByTime(10000))
  expect(container.querySelector('.star-pet__image')?.getAttribute('src')).toBe('./mascot/poses/type-1.png')
 })
 it('shows and hides status when clicked',async()=>{
  const user=userEvent.setup()
  render(<StarPet state="update"/>)
  const button=screen.getByRole('button',{name:'Star mascot'})
  await user.click(button)
  expect(screen.getByRole('status').textContent).toContain('update')
  expect(button.getAttribute('aria-expanded')).toBe('true')
  await user.click(button)
  expect(screen.queryByRole('status')).toBeNull()
 })
 it.each(['{Enter}',' '] as const)('opens status with keyboard activation %s',async key=>{
  const user=userEvent.setup()
  render(<StarPet state="update"/>)
  await user.tab()
  expect(document.activeElement).toBe(screen.getByRole('button',{name:'Star mascot'}))
  await user.keyboard(key)
  expect(screen.getByRole('status').textContent).toContain('update')
  await user.keyboard(key)
  expect(screen.queryByRole('status')).toBeNull()
 })
 it.each([false,true])('does not toggle after a drag (reduced motion: %s)',reducedMotion=>{
  render(<StarPet state="update" reducedMotion={reducedMotion}/>)
  const button=screen.getByRole('button',{name:'Star mascot'})
  // MouseEvent supplies coordinates even when jsdom has no PointerEvent constructor.
  fireEvent(button,new MouseEvent('pointerdown',{bubbles:true,clientX:400,clientY:400}))
  fireEvent(button,new MouseEvent('pointerup',{bubbles:true,clientX:10,clientY:10}))
  fireEvent.click(button,{detail:1})
  expect(screen.queryByRole('status')).toBeNull()
  expect(localStorage.getItem('star.pet.corner')).toBe(reducedMotion?null:'top-left')
  fireEvent.click(button,{detail:1})
  expect(screen.getByRole('status').textContent).toContain('update')
 })
 it('does not swallow keyboard activation after a drag without a click',async()=>{
  const user=userEvent.setup()
  render(<StarPet state="update"/>)
  const button=screen.getByRole('button',{name:'Star mascot'})
  fireEvent(button,new MouseEvent('pointerdown',{bubbles:true,clientX:400,clientY:400}))
  fireEvent(button,new MouseEvent('pointerup',{bubbles:true,clientX:10,clientY:10}))
  button.focus()
  await user.keyboard('{Enter}')
  expect(screen.getByRole('status').textContent).toContain('update')
 })
 it('sleeps only after idle time and resets after a long answer',()=>{
  vi.useFakeTimers()
  const {rerender}=render(<StarPet state="idle" reducedMotion/>)
  act(()=>vi.advanceTimersByTime(600000))
  expect(screen.getByTestId('star-pet').getAttribute('data-state')).toBe('sleepy')
  act(()=>vi.advanceTimersByTime(60000))
  expect(screen.getByTestId('star-pet').getAttribute('data-state')).toBe('asleep')
  rerender(<StarPet state="thinking" reducedMotion/>)
  expect(vi.getTimerCount()).toBe(0)
  act(()=>vi.advanceTimersByTime(900000))
  rerender(<StarPet state="streaming" reducedMotion/>)
  rerender(<StarPet state="finished" reducedMotion/>)
  rerender(<StarPet state="idle" reducedMotion/>)
  expect(screen.getByTestId('star-pet').getAttribute('data-state')).toBe('idle')
  act(()=>vi.advanceTimersByTime(30000))
  expect(screen.getByTestId('star-pet').getAttribute('data-state')).toBe('idle')
 })
})

describe('pet idle clock',()=>{
 it('caps at 700000 ms and resets on pointer and keyboard activity',()=>{
  vi.useFakeTimers()
  const {result,unmount}=renderHook(()=>usePetIdleMs(true))
  act(()=>vi.advanceTimersByTime(900000))
  expect(result.current).toBe(700000)
  act(()=>vi.advanceTimersByTime(900000))
  expect(result.current).toBe(700000)
  fireEvent.pointerDown(window)
  expect(result.current).toBe(0)
  act(()=>vi.advanceTimersByTime(30000))
  expect(result.current).toBe(30000)
  fireEvent.keyDown(window,{key:'a'})
  expect(result.current).toBe(0)
  unmount()
  expect(vi.getTimerCount()).toBe(0)
 })
 it('does not start when inactive and cleans up when disabled',()=>{
  vi.useFakeTimers()
  const {result,rerender}=renderHook(({active})=>usePetIdleMs(active),{initialProps:{active:false}})
  expect(vi.getTimerCount()).toBe(0)
  rerender({active:true})
  act(()=>vi.advanceTimersByTime(60000))
  expect(result.current).toBe(60000)
  rerender({active:false})
  expect(result.current).toBe(0)
  expect(vi.getTimerCount()).toBe(0)
  act(()=>vi.advanceTimersByTime(900000))
  expect(result.current).toBe(0)
 })
})
