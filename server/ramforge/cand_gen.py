#!/usr/bin/env python3
"""RAMForge cand_gen: generate a kernel variant from the shipped ggml source (the "mutation" step of an
AlphaEvolve-style loop; today the mutations are hand-written, an LLM proposer can replace `mutate`).

Usage: cand_gen.py <llama.cpp src> <variant> <out.cpp>
variants:
  copy          the shipped AVX2 q4_K 8x8 gemv, renamed (sanity check: must time like the shipped kernel)
  pfN           + software prefetch of all cache lines of block b+N of the current 8-row group (N = 1, 2, 4 ...)
  pfrowN        + prefetch of the next 8-row group's block b, N lines ahead
The output defines rf_candidate_gemv_q4_K_8x8 and is linked into kernel_lab with -DRF_HAVE_CAND.
"""
import re
import sys

src, variant, out = sys.argv[1], sys.argv[2], sys.argv[3]
path = f"{src}/ggml/src/ggml-cpu/arch/x86/repack.cpp"
text = open(path).read()
name = "void ggml_gemv_q4_K_8x8_q8_K("
start = text.index(name)
# preamble: everything before the first exported kernel (keeps the file's macros and static helpers)
first = re.search(r"^void ggml_", text, re.M).start()
preamble = text[:first]
# brace-match the target function
i = text.index("{", start); depth = 0; j = i
while True:
    if text[j] == "{": depth += 1
    elif text[j] == "}":
        depth -= 1
        if depth == 0: break
    j += 1
func = text[start:j + 1].replace("void ggml_gemv_q4_K_8x8_q8_K(", 'extern "C" void rf_candidate_gemv_q4_K_8x8(', 1)

anchor = "            for (int64_t b = 0; b < nb; b++) {\n"
if anchor not in func:
    sys.exit("anchor not found: kernel source changed, update cand_gen.py")
if variant == "copy":
    pass
elif variant.startswith("pfrow"):
    n = int(variant[5:])
    func = func.replace(anchor, anchor + (
        "                { const char * pf = (const char *) (b_ptr + b_nb + b);\n"
        "                  for (int l = 0; l < (int) sizeof(block_q4_Kx8); l += 64 * %d) _mm_prefetch(pf + l, _MM_HINT_T0); }\n" % n), 1)
elif variant.startswith("pf"):
    n = int(variant[2:])
    func = func.replace(anchor, anchor + (
        "                if (b + %d < nb) { const char * pf = (const char *) (b_ptr + b + %d);\n"
        "                  for (int l = 0; l < (int) sizeof(block_q4_Kx8); l += 64) _mm_prefetch(pf + l, _MM_HINT_T0); }\n" % (n, n)), 1)
else:
    sys.exit("unknown variant " + variant)
open(out, "w").write("// generated by cand_gen.py, variant " + variant + "\n" + preamble + "\n" + func + "\n")
print("wrote", out, variant)
