"""The running report: kept / rejected per gate, examples per hour, where the time went."""
from __future__ import annotations

from datetime import datetime, timezone
import json
from pathlib import Path

from .quiet import atomic_write_text
from .store import Store, read_jsonl

GATE_ORDER = ["T", "S", "G0", "G6", "G8", "G7", "G1", "G2", "G3", "G4"]
GATE_TEXT = {
    "T": "task writer reply unusable", "S": "solver reply unusable", "G0": "shape / headers / forbidden calls",
    "G6": "deprecated API", "G8": "overlaps the evaluation suites", "G7": "near-duplicate",
    "G1": "does not compile", "G2": "type analysis", "G3": "tests fail in the Luau VM", "G4": "test sanity (stub / mutants)",
}


def _parse(ts: str) -> datetime:
    return datetime.strptime(ts, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)


def summary(store: Store) -> dict:
    st = store.state
    kept_rows = read_jsonl(store.kept_path)
    rej = st["rejected"]
    rejected_total = sum(sum(v.values()) for v in rej.values())
    active_h = st["seconds"]["active"] / 3600.0
    first = _parse(st["created"])
    wall_h = max((datetime.now(timezone.utc) - first).total_seconds() / 3600.0, 1e-9)
    paused = {k: round(v, 1) for k, v in st["paused"].items()}
    per_hour_active = st["kept"] / active_h if active_h > 0.01 else 0.0
    cand_per_hour = st["candidates"] / active_h if active_h > 0.01 else 0.0
    out = {
        "generated": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "candidates": st["candidates"], "kept": st["kept"], "rejected": rejected_total,
        "yield": round(st["kept"] / st["candidates"], 3) if st["candidates"] else 0.0,
        "active_hours": round(active_h, 3), "wall_hours_since_first_start": round(wall_h, 2),
        "kept_per_active_hour": round(per_hour_active, 2), "candidates_per_active_hour": round(cand_per_hour, 2),
        "kept_per_wall_hour": round(st["kept"] / wall_h, 2),
        "rejected_by_gate": {g: rej[g] for g in GATE_ORDER if g in rej} | {g: v for g, v in rej.items() if g not in GATE_ORDER},
        "tokens": st["tokens"], "seconds": {k: round(v, 1) for k, v in st["seconds"].items()},
        "paused_seconds": paused, "infra_errors": st["infra_errors"], "runs": st["runs"][-5:],
        "by_category": st["by_category"],
        "eta": {},
    }
    if per_hour_active > 0:
        left = max(0, 800 - st["kept"])
        out["eta"] = {
            "examples_left_to_800": left,
            "active_hours_to_800": round(left / per_hour_active, 1),
            "nights_of_5h": round(left / per_hour_active / 5.0, 1),
            "nights_of_6h": round(left / per_hour_active / 6.0, 1),
        }
    kills = [r["gates"]["G4"].get("kill_rate") for r in kept_rows if r.get("gates", {}).get("G4", {}).get("kill_rate") is not None]
    out["mean_kill_rate_of_kept"] = round(sum(kills) / len(kills), 3) if kills else None
    out["kept_by_mode"] = {m: sum(1 for r in kept_rows if r.get("mode") == m) for m in ("pure", "mock")}
    return out


def render(info: dict) -> str:
    lines = [
        "# Training-data generator: running report",
        "",
        f"Updated {info['generated']}. Kept **{info['kept']}** of {info['candidates']} candidates "
        f"(yield {info['yield'] * 100:.1f} percent). Active time {info['active_hours']} h "
        f"(wall time since first start {info['wall_hours_since_first_start']} h).",
        "",
        f"- Kept per active hour: **{info['kept_per_active_hour']}**; candidates per active hour: {info['candidates_per_active_hour']}.",
        f"- Kept per wall hour including pauses: {info['kept_per_wall_hour']}.",
        f"- Kept by mode: {info['kept_by_mode']}; mean mutant kill rate of kept examples: {info['mean_kill_rate_of_kept']}.",
        f"- Tokens generated by the teachers: {info['tokens']['completion']} (prompt tokens read: {info['tokens']['prompt']}).",
        f"- Time: {info['seconds']}. Paused / dropped: {info['paused_seconds']}. Infrastructure errors: {info['infra_errors']}.",
    ]
    if info["eta"]:
        e = info["eta"]
        lines.append(f"- To reach 800 kept: {e['examples_left_to_800']} more = {e['active_hours_to_800']} active hours "
                     f"= {e['nights_of_5h']} nights of 5 h ({e['nights_of_6h']} nights of 6 h).")
    lines += ["", "## Rejected, by the first gate that failed", "", "| Gate | What | Reason | Count |", "|---|---|---|---|"]
    for gate, reasons in info["rejected_by_gate"].items():
        for code, n in sorted(reasons.items(), key=lambda kv: -kv[1]):
            lines.append(f"| {gate} | {GATE_TEXT.get(gate, '')} | {code} | {n} |")
    lines += ["", "## By category", "", "| Category | Candidates | Kept |", "|---|---|---|"]
    for cat, v in sorted(info["by_category"].items(), key=lambda kv: -kv[1]["candidates"]):
        lines.append(f"| {cat} | {v['candidates']} | {v['kept']} |")
    lines += ["", "## Recent runs", ""]
    for run in info["runs"]:
        lines.append(f"- {run.get('start')} to {run.get('stop') or 'running'}: {run.get('candidates')} candidates, {run.get('kept')} kept")
    return "\n".join(lines) + "\n"


def write(store: Store, out_dir: Path) -> dict:
    info = summary(store)
    atomic_write_text(out_dir / "report.json", json.dumps(info, indent=1, sort_keys=True))
    atomic_write_text(out_dir / "report.md", render(info))
    return info
