"""Generate developer API reference Markdown for STAR's main Python modules.

Static (AST-based): modules are parsed, never imported, so generating the docs
runs no STAR code and needs no optional dependencies.

    python scripts/gen_api_docs.py            # write docs/dev/api/*.md
    python scripts/gen_api_docs.py --check    # exit 1 if the docs are stale
"""
from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "dev" / "api"

# Module path (relative to repo root) for each documented module.
MODULES = [
    "star/agent.py",
    "star/desktop_core.py",
    "star/providers.py",
    "star/intelligence.py",
    "star/skill_packs/__init__.py",
    "star/lessons.py",
    "star/learned_week.py",
    "star/corrections.py",
    "star/map_plan.py",
    "star/design_db.py",
    "star/design_md.py",
    "star/design_system.py",
]


def _name(path: str) -> str:
    parts = Path(path).with_suffix("").parts
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def _sig(node: ast.AST) -> str:
    args = ast.unparse(node.args)  # type: ignore[attr-defined]
    ret = f" -> {ast.unparse(node.returns)}" if node.returns else ""  # type: ignore[attr-defined]
    kind = "async def" if isinstance(node, ast.AsyncFunctionDef) else "def"
    return f"{kind} {node.name}({args}){ret}"  # type: ignore[attr-defined]


def _doc(node: ast.AST) -> str:
    return (ast.get_docstring(node) or "").strip()  # type: ignore[arg-type]


def _public(name: str) -> bool:
    return not name.startswith("_")


def _entry(node: ast.AST, level: str) -> list[str]:
    out = [f"{level} `{node.name}`", "", "```python", _sig(node), "```", ""]  # type: ignore[attr-defined]
    doc = _doc(node)
    if doc:
        out += [doc, ""]
    return out


def render(path: str) -> str:
    tree = ast.parse((ROOT / path).read_text(encoding="utf-8"))
    mod = _name(path)
    lines = [f"# `{mod}`", "", f"Source: `{path}`", ""]
    doc = _doc(tree)
    if doc:
        lines += [doc, ""]
    consts = []
    for n in tree.body:
        if isinstance(n, ast.Assign):
            for t in n.targets:
                if isinstance(t, ast.Name) and t.id.isupper() and _public(t.id):
                    consts.append(t.id)
    if consts:
        lines += ["## Constants", "", ", ".join(f"`{c}`" for c in consts), ""]
    classes = [n for n in tree.body if isinstance(n, ast.ClassDef) and _public(n.name)]
    funcs = [
        n
        for n in tree.body
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and _public(n.name)
    ]
    if classes:
        lines += ["## Classes", ""]
        for c in classes:
            bases = ", ".join(ast.unparse(b) for b in c.bases)
            lines += [f"### `{c.name}`" + (f"({bases})" if bases else ""), ""]
            if _doc(c):
                lines += [_doc(c), ""]
            for m in c.body:
                if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef)) and (
                    _public(m.name) or m.name == "__init__"
                ):
                    lines += _entry(m, "####")
    if funcs:
        lines += ["## Functions", ""]
        for f in funcs:
            lines += _entry(f, "###")
    return "\n".join(lines).rstrip() + "\n"


def build() -> dict[Path, str]:
    files: dict[Path, str] = {}
    index = [
        "# STAR developer API reference",
        "",
        "Generated by `python scripts/gen_api_docs.py` (static AST; nothing is imported).",
        "Do not edit by hand; edit the docstrings and regenerate.",
        "",
    ]
    for path in MODULES:
        mod = _name(path)
        files[OUT / f"{mod}.md"] = render(path)
        summary = _doc(ast.parse((ROOT / path).read_text(encoding="utf-8"))).split("\n")[0]
        index.append(f"- [`{mod}`]({mod}.md) - {summary}")
    files[OUT / "README.md"] = "\n".join(index) + "\n"
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if generated docs are stale")
    args = ap.parse_args()
    files = build()
    if args.check:
        stale = [
            str(p.relative_to(ROOT))
            for p, text in files.items()
            if not p.exists() or p.read_text(encoding="utf-8") != text
        ]
        if stale:
            print("stale API docs:", *stale, sep="\n  ")
            return 1
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for p, text in files.items():
        p.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(files)} files to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
